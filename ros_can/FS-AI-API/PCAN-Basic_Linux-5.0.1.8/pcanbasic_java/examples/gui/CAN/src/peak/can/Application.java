    // Returns selected non-connected TPCANHandle
    private TPCANHandle getSelectedChannel() {
        TPCANHandle handle = TPCANHandle.PCAN_NONEBUS;
        String strTemp = jComboBoxChannel.getSelectedItem().toString();

        try {
            int idx = strTemp.indexOf('(') + 1;
            strTemp = strTemp.substring(idx, idx + 3);
            short value = Short.parseShort(strTemp, 16);
            for (TPCANHandle h : TPCANHandle.values()) {
                if (h.getValue() == value) {
                    handle = h;
                    break;
                }
            }
        }
        catch (NumberFormatException ex) {}
        return handle;
    }

