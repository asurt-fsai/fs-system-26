    class CANProtocol {
        public final static int CAN_CC = (1<<1);
        public final static int CAN_FD = (1<<2);
        public final static int CAN_XL = (1<<3);
    }

    private String FormatChannelName(TPCANHandle handle, int protocol)
    {
        TPCANDevice devDevice = TPCANDevice.PCAN_NONE;
        byte byDevDevice;

        byte byChannel;

        // Gets the owner device and channel for a
        // PCAN-Basic handle
        //
        if (handle.getValue() < 0x100)
        {
            byDevDevice = (byte)(handle.getValue() >> 4);
            byChannel = (byte)(handle.getValue() & 0xF);
        }
        else
        {
            byDevDevice = (byte)(handle.getValue() >> 8);
            byChannel = (byte)(handle.getValue() & 0xFF);
        }
        for (TPCANDevice d : TPCANDevice.values()) {
            if (d.getValue() == byDevDevice) {
                devDevice = d;
                break;
            }
        }
        // Constructs the PCAN-Basic Channel name and return it
        //
        String stringFormat = "%s%s %d (%03Xh)";
        Boolean bIsXL = (protocol & CANProtocol.CAN_XL) == CANProtocol.CAN_XL;
        Boolean bIsFd = (protocol & CANProtocol.CAN_FD) == CANProtocol.CAN_FD;

        if (bIsXL && bIsFd)
            return String.format(stringFormat, devDevice, ":FD/XL", byChannel, handle.getValue());
        else if (bIsXL)
            return String.format(stringFormat, devDevice, ":XL", byChannel, handle.getValue());
        else if (bIsFd)
            return String.format(stringFormat, devDevice, ":FD", byChannel, handle.getValue());
        else
            return String.format(stringFormat, devDevice, "", byChannel, handle.getValue());
    }

